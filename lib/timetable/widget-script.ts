import { BLOCK_COLORS } from "@/lib/timetable/constants";

// Builds the Scriptable (iOS) script shown on the Timetable page for the
// user to paste into the app. It fetches /api/timetable and works out
// "now"/"next" with the phone's own clock, so it follows the phone's
// timezone. Supports lock-screen (rectangular, inline) and home-screen
// (small/medium/large) widget sizes. The last good response is cached on the
// phone so the widget still shows something when offline.
export function buildWidgetScript(apiUrl: string, token: string): string {
  const colors = Object.fromEntries(Object.entries(BLOCK_COLORS).map(([k, v]) => [k, v.hex]));

  return `// Timetable widget — generated by your dashboard.
// Add to the lock screen as a rectangular or inline widget, or to the home
// screen at any size. Running it in the app shows a preview.

const API_URL = ${JSON.stringify(apiUrl)};
const TOKEN = ${JSON.stringify(token)};
const COLORS = ${JSON.stringify(colors)};

const fm = FileManager.local();
const cachePath = fm.joinPath(fm.documentsDirectory(), "timetable-cache.json");

async function loadBlocks() {
  try {
    const req = new Request(API_URL);
    req.headers = { Authorization: "Bearer " + TOKEN };
    req.timeoutInterval = 10;
    const data = await req.loadJSON();
    if (!Array.isArray(data.blocks)) throw new Error(data.error || "Unexpected response");
    fm.writeString(cachePath, JSON.stringify(data.blocks));
    return data.blocks;
  } catch (e) {
    if (fm.fileExists(cachePath)) return JSON.parse(fm.readString(cachePath));
    throw e;
  }
}

const toMin = (t) => {
  const [h, m] = t.split(":").map(Number);
  return h * 60 + m;
};

function atMinutes(base, minutes) {
  const d = new Date(base);
  d.setHours(0, 0, 0, 0);
  d.setMinutes(minutes);
  return d;
}

const now = new Date();
const nowMin = now.getHours() * 60 + now.getMinutes();
const pad = (n) => String(n).padStart(2, "0");
const todayStr = now.getFullYear() + "-" + pad(now.getMonth() + 1) + "-" + pad(now.getDate());
const family = config.widgetFamily;
const w = new ListWidget();

let blocks = null;
let error = null;
try {
  blocks = (await loadBlocks())
    // One-off blocks show on their own date; weekly blocks on their weekdays.
    .filter((b) => (b.date ? b.date === todayStr : b.days.includes(now.getDay())))
    .sort((a, b) => toMin(a.startTime) - toMin(b.startTime));
} catch (e) {
  error = e;
}

if (error) {
  const t = w.addText(family === "accessoryInline" ? "Timetable offline" : "Timetable: can't connect");
  t.font = Font.systemFont(12);
  w.refreshAfterDate = new Date(Date.now() + 15 * 60 * 1000);
} else {
  const current = blocks.find((b) => toMin(b.startTime) <= nowMin && nowMin < toMin(b.endTime));
  const next = blocks.find((b) => toMin(b.startTime) > nowMin);

  // Ask iOS to refresh when the current block ends or the next one starts.
  // iOS treats this as a hint, so it may run a few minutes late.
  const boundaries = [current && toMin(current.endTime), next && toMin(next.startTime)].filter(
    (m) => m !== undefined && m !== null,
  );
  w.refreshAfterDate = boundaries.length
    ? atMinutes(now, Math.min(...boundaries))
    : atMinutes(new Date(now.getTime() + 24 * 60 * 60 * 1000), 1);

  if (family === "accessoryInline") {
    const text = current
      ? current.title + " until " + current.endTime
      : next
        ? "Next " + next.startTime + " " + next.title
        : "Nothing else today";
    w.addText(text);
  } else if (family === "accessoryCircular") {
    w.addAccessoryWidgetBackground = true;
    const label = w.addText(current ? "until" : "next");
    label.font = Font.systemFont(10);
    label.centerAlignText();
    const time = w.addText(current ? current.endTime : next ? next.startTime : "—");
    time.font = Font.boldSystemFont(13);
    time.centerAlignText();
  } else if (family === "accessoryRectangular") {
    w.addAccessoryWidgetBackground = true;
    const head = w.addText(current ? current.title : next ? "Free" : "Done for today");
    head.font = Font.boldSystemFont(15);
    head.lineLimit = 1;
    const sub = w.addText(current ? current.startTime + " – " + current.endTime : next ? "until " + next.startTime : " ");
    sub.font = Font.systemFont(12);
    sub.textOpacity = 0.8;
    if (current && next) {
      const n = w.addText("Next " + next.startTime + " " + next.title);
      n.font = Font.systemFont(12);
      n.textOpacity = 0.8;
      n.lineLimit = 1;
    }
  } else {
    // Home screen (or the in-app preview): the rest of today's day.
    w.backgroundColor = new Color("#0a0a0a");
    w.setPadding(12, 14, 12, 14);
    const title = w.addText("Today");
    title.font = Font.boldSystemFont(13);
    title.textColor = new Color("#a3a3a3");
    w.addSpacer(6);

    const maxRows = family === "large" ? 12 : family === "medium" ? 5 : 4;
    const firstIndex = Math.max(
      0,
      blocks.findIndex((b) => toMin(b.endTime) > nowMin),
    );
    const visible = blocks.slice(firstIndex, firstIndex + maxRows);
    if (visible.length === 0 || blocks.every((b) => toMin(b.endTime) <= nowMin)) {
      const t = w.addText("Nothing else today");
      t.font = Font.systemFont(13);
      t.textColor = Color.white();
    }
    for (const b of visible) {
      if (toMin(b.endTime) <= nowMin) continue;
      const isNow = b === current;
      const row = w.addStack();
      row.centerAlignContent();
      const bar = row.addStack();
      bar.size = new Size(3, 16);
      bar.cornerRadius = 1.5;
      bar.backgroundColor = new Color(COLORS[b.color] || COLORS.violet);
      row.addSpacer(6);
      const time = row.addText(family === "small" ? b.startTime : b.startTime + "–" + b.endTime);
      time.font = Font.mediumMonospacedSystemFont(11);
      time.textColor = new Color(isNow ? "#ffffff" : "#a3a3a3");
      row.addSpacer(6);
      const name = row.addText(b.title);
      name.font = isNow ? Font.boldSystemFont(13) : Font.systemFont(13);
      name.textColor = Color.white();
      name.lineLimit = 1;
      w.addSpacer(4);
    }
    w.addSpacer();
  }
}

if (config.runsInWidget) {
  Script.setWidget(w);
} else {
  await w.presentMedium();
}
Script.complete();
`;
}
